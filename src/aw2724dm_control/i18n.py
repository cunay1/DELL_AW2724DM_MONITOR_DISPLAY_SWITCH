def normalize_language(value: Any) -> str:
    return str(value).lower() if str(value).lower() in SUPPORTED_LANGUAGES else "en"


def set_language(value: Any) -> str:
    global _language
    _language = normalize_language(value)
    return _language


def get_language() -> str:
    return _language


